#include <cassert>
#include <cstdint>
#include <span>
#include <string>
#include <vector>

#include "utils/ImageRaster.hpp"

namespace {

// 1x1 opaque red PNG.
constexpr uint8_t kOneByOnePng[] = {
    0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D,
    0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
    0x08, 0x02, 0x00, 0x00, 0x00, 0x90, 0x77, 0x53, 0xDE, 0x00, 0x00, 0x00,
    0x0C, 0x49, 0x44, 0x41, 0x54, 0x08, 0xD7, 0x63, 0xF8, 0xCF, 0xC0, 0x00,
    0x00, 0x03, 0x01, 0x01, 0x00, 0x18, 0xDD, 0x8D, 0xB0, 0x00, 0x00, 0x00,
    0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
};

} // namespace

int main() {
    std::string error;
    const auto image = arc_helper::NormalizeBackgroundImage(
        std::span<const uint8_t>(kOneByOnePng, sizeof(kOneByOnePng)), &error);
    assert(image);
    assert(error.empty());
    assert(image->source_width == 1);
    assert(image->source_height == 1);
    assert(image->resized);
    assert(image->jpeg.size() > 32);
    assert(image->jpeg[0] == 0xFF && image->jpeg[1] == 0xD8);
    return 0;
}
